using System;

namespace World.Planet;

// 星球常数集中管理（用户 2026-10-08 拍板）。
// ── 为什么集中 ────────────────────────────────────────────────────────────
// 物理常数（σ、Q₀、Γ…）是**世界的客观属性**，不属于任何单一模型；散在各模型类里
// 会导致：① 同一个常数多处各写一遍（如 EarthRadiusKm 曾在两处重复）；② 标定时
// 找不到全量清单；③ 改一处漏一处 ⇒ 静默不一致。
// ── 组织方式 ──────────────────────────────────────────────────────────────
// 跨领域常数放本类；**领域常数各自独立成文件**（`Thermal.cs`、后续 `Fluid.cs`…
// 同为 `World.Planet` 命名空间），按物理领域分组、便于扩展与检索。
/// <summary>
/// 星球常数（真实地球值）。跨领域几何等放本类；领域常数见同命名空间下的
/// <see cref="Thermal"/> 等独立类。
/// </summary>
public static class PlanetConstants
{
    /// <summary>地球平均半径（km）。</summary>
    public const float EarthRadiusKm = 6371f;

}
